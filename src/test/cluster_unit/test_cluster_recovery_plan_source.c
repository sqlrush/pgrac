static void
reset_plan_fixture(void)
{
	memset(&published_plan, 0, sizeof(published_plan));
	memset(roots, 0, sizeof(roots));
	published = latch_active = registry_ready = false;
	root_reads = registry_checks = registry_reads = restores = warnings = 0;
	cluster_shared_config = true;
	own_thread = 1;
	cluster_wal_threads_dir = "fixture-wal";
	cluster_recovery_plan_shmem = &published_plan;
	for (unsigned tid = 1; tid <= 4; tid++) {
		root_result[tid] = CLUSTER_CONTROL_ROOT_OK_PRIMARY;
		roots[tid].identity.origin_node_id = tid - 1;
		roots[tid].lifecycle = CLUSTER_CONTROL_ROOT_LIFECYCLE_RECOVERY_REQUIRED;
		roots[tid].checkpoint_lower_lsn = 100 * tid;
		roots[tid].validated_tail_lsn_exclusive = 100 * tid + 50;
	}
}

UT_TEST(test_pre2_creation_cold_plan_uses_root_without_migration_latch)
{
	reset_plan_fixture();
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(published && published_plan.generated && !published_plan.failed);
	UT_ASSERT_EQ(published_plan.n_crashed_candidate, 3);
	UT_ASSERT_EQ(published_plan.n_alive, 0);
	UT_ASSERT_EQ(published_plan.n_unknown, 0);
	UT_ASSERT_EQ(published_plan.n_empty, CLUSTER_RECOVERY_PLAN_THREADS - 4);
	UT_ASSERT_EQ(published_plan.threads_scanned, CLUSTER_RECOVERY_PLAN_THREADS);
	UT_ASSERT_EQ(published_plan.max_highest_lsn, 450);
	UT_ASSERT_EQ(root_reads, CLUSTER_RECOVERY_PLAN_THREADS);
	UT_ASSERT_EQ(registry_checks + registry_reads + warnings, 0);
	UT_ASSERT(!latch_active);
}

UT_TEST(test_every_pre2_startup_uses_its_own_physical_root_roster)
{
	for (unsigned own = 1; own <= 4; own++) {
		reset_plan_fixture();
		own_thread = own;
		cluster_recovery_plan_generate(1, true);
		UT_ASSERT(published && !published_plan.failed);
		UT_ASSERT_EQ(published_plan.n_crashed_candidate, 3);
		for (uint16 tid = 1; tid <= 4; tid++)
			UT_ASSERT_EQ(cluster_recovery_plan_candidate_test(&published_plan, tid), tid != own);
		UT_ASSERT_EQ(registry_checks + registry_reads, 0);
	}
}

UT_TEST(test_pre2_bad_root_stays_unknown_without_registry_fallback)
{
	reset_plan_fixture();
	registry_ready = true;
	root_result[2] = CLUSTER_CONTROL_ROOT_BAD_BODY_CRC;
	roots[3].identity.origin_node_id = 99;
	root_result[4] = CLUSTER_CONTROL_ROOT_IO_ERROR;
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(published && !published_plan.failed);
	UT_ASSERT_EQ(published_plan.n_unknown, 3);
	UT_ASSERT_EQ(published_plan.n_crashed_candidate, 0);
	UT_ASSERT_EQ(registry_checks + registry_reads, 0);
}

UT_TEST(test_pre2_root_alive_clean_and_degraded_polarities_are_unchanged)
{
	reset_plan_fixture();
	roots[2].lifecycle = CLUSTER_CONTROL_ROOT_LIFECYCLE_OPEN;
	roots[2].published_at_usec = GetCurrentTimestamp();
	roots[3].lifecycle = CLUSTER_CONTROL_ROOT_LIFECYCLE_CLOSED;
	root_result[4] = CLUSTER_CONTROL_ROOT_OK_PRIMARY_DEGRADED;
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(published && !published_plan.failed);
	UT_ASSERT_EQ(published_plan.n_alive, 1);
	UT_ASSERT_EQ(published_plan.n_clean, 1);
	UT_ASSERT_EQ(published_plan.n_crashed_candidate, 1);
	UT_ASSERT(cluster_recovery_plan_candidate_test(&published_plan, 4));
	UT_ASSERT(!cluster_recovery_plan_candidate_test(&published_plan, 2));
}

UT_TEST(test_legacy_source_still_requires_its_registry)
{
	reset_plan_fixture();
	cluster_shared_config = false;
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(published && published_plan.generated && published_plan.failed);
	UT_ASSERT_EQ(registry_checks, 1);
	UT_ASSERT_EQ(root_reads + registry_reads, 0);
	UT_ASSERT_EQ(warnings, 1);
	reset_plan_fixture();
	cluster_shared_config = false;
	registry_ready = true;
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(published && !published_plan.failed);
	UT_ASSERT_EQ(registry_reads, CLUSTER_RECOVERY_PLAN_THREADS);
	UT_ASSERT_EQ(root_reads, 0);
}

UT_TEST(test_legacy_target_still_uses_restored_migration_latch)
{
	reset_plan_fixture();
	cluster_shared_config = false;
	latch_active = true;
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(published && !published_plan.failed);
	UT_ASSERT_EQ(restores, 1);
	UT_ASSERT_EQ(root_reads, CLUSTER_RECOVERY_PLAN_THREADS);
	UT_ASSERT_EQ(registry_checks + registry_reads, 0);
}

UT_TEST(test_unconfigured_or_missing_shmem_never_publishes)
{
	reset_plan_fixture();
	cluster_wal_threads_dir = "";
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(!published);
	reset_plan_fixture();
	cluster_recovery_plan_shmem = NULL;
	cluster_recovery_plan_generate(1, true);
	UT_ASSERT(!published);
	UT_ASSERT_EQ(root_reads + registry_reads, 0);
}

