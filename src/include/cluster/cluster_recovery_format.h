/* Pure RFI2 codecs. Complete original control/custody validation belongs to
 * the caller. Short/unknown/malformed/aliasing inputs refuse, preserving
 * outputs. Only the assigned format ID/version and known kinds are accepted.
 * No file I/O, allocation, custody or success-state mutation.
 * Implemented by the common owner before any runtime consumer is linked. */
